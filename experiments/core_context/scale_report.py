"""Per-batch and cumulative tables of the read-site search from each batch's acceptance.json, cleanup.json and
archive.json. Real batches, development and the computational positive test are kept in separate groups.

  python scale_report.py scale_comamonadaceae_v0.1 > scale_comamonadaceae_v0.1/read_site_search_scale_report.md
"""
import json
import sys
from collections import Counter
from pathlib import Path

GROUPS = (('development (regression cases, not validation)', ['pilot']),
          ('real, not used in development', ['validation1', 'validation2', 'scale1', 'scale2', 'scale3']),
          ('computational positive test (edited assemblies; scored against truth only)', ['positive1']))
CATS = ('known', 'in_assembly_not_in_catalog', 'not_in_assembly_candidate', 'structural_anomaly', 'unresolved')


def frac(s):
    a, b = s.split('/')
    return int(a), int(b)


def load(d, b):
    p = d / ('read_site_search_' + b)
    if not (p / 'acceptance.json').exists():
        return None
    acc = json.loads((p / 'acceptance.json').read_text())
    cl = json.loads((p / 'cleanup.json').read_text()) if (p / 'cleanup.json').exists() else {}
    ar = json.loads((p / 'archive.json').read_text()) if (p / 'archive.json').exists() else {}
    return dict(batch=b, acc=acc, freed=cl.get('bytes_freed', 0) if cl.get('applied') else 0,
                archive=ar.get('sha256', '')[:12])


def row(r):
    a, s = r['acc'], r['acc']['sites']
    st = Counter(a['sample_status'])
    rec = {k: frac(v) for k, v in a['known_recovery'].items()}
    nc = s['negative_control_sites_per_gene']['genes_by_site_count']
    nia = s['not_in_assembly_candidates']
    struct = Counter(a.get('candidates_reviewed', {}).get('structure', {}))
    return dict(
        batch=r['batch'], samples=a['expected_samples'], complete=st.get('complete', 0),
        failed=sum(v for k, v in st.items() if k.startswith(('fail', 'mismatch'))),
        awaiting_input=sum(v for k, v in st.items() if 'input' in k),
        rec5='%d/%d' % rec.get('core|round5_supported', (0, 0)),
        rec_other='%d/%d' % rec.get('core|not_round5_supported', (0, 0)),
        nc='%s' % ', '.join('%s site: %d' % (k, v) for k, v in sorted(nc.items())),
        **{c: s['sites_by_category'].get(c, 0) for c in CATS},
        nia_positions=nia['positions'], nia_cores=nia['cores'], nia_samples=nia['samples'],
        met=sum(v for k, v in struct.items() if k.endswith('|met')),
        target_unresolved=sum(v for k, v in struct.items() if 'unresolved' in k),
        not_met=sum(v for k, v in struct.items() if k.endswith('|not_met')),
        other_status=sum(v for k, v in struct.items() if not k.startswith('checked')),
        boundary_unknown=s['flags_of_counted_sites'].get('boundary_unknown', 0),
        truncated=s['unplaceable_contexts_ge_N'].get('inner_end_unaligned (alignment truncated)', 0),
        ambiguous=s['unplaceable_contexts_ge_N'].get('ambiguous_placement (repeat)', 0),
        rss=a['max_rss_gb'], freed_gb=round(r['freed'] / 1e9, 2), archive=r['archive'])


COLS = ('batch', 'samples', 'complete', 'failed', 'awaiting_input', 'rec5', 'rec_other', 'nc') + CATS + (
    'nia_positions', 'nia_cores', 'nia_samples', 'met', 'target_unresolved', 'not_met', 'other_status', 'boundary_unknown',
    'truncated', 'ambiguous', 'rss', 'freed_gb', 'archive')
HEAD = ('batch', 'samples', 'complete', 'failed', 'awaiting input', 'recovery round5', 'recovery other',
        'negative control genes by site count', 'known', 'in assembly, not catalogued', 'not-in-assembly candidate sites',
        'structural anomaly', 'unresolved', 'candidate positions', 'candidate cores', 'candidate samples',
        'target met', 'target unresolved', 'target not met', 'consensus not built', 'boundary unknown',
        'truncated alignment', 'ambiguous placement', 'max RSS GB', 'cleanup freed GB', 'archive sha256')


def total(rows):
    t = dict(batch='**total**')
    for c in COLS[1:]:
        v = [r[c] for r in rows]
        if c in ('rec5', 'rec_other'):
            t[c] = '%d/%d' % tuple(map(sum, zip(*(frac(x) for x in v))))
        elif c == 'rss':
            t[c] = max(v)
        elif c in ('nc', 'archive'):
            t[c] = ''
        else:
            t[c] = round(sum(v), 2)
    return t


def main():
    d = Path(sys.argv[1])
    print('Generated by `scale_report.py` from each batch\'s acceptance.json / cleanup.json / archive.json. Counts '
          'are sites (physical places, cores merged) at flanks 1 kb, at least 3 molecules; the candidate '
          'positions / cores / samples are counted separately. Real batches and the computational test are never '
          'summed together.\n')
    for name, batches in GROUPS:
        rows = [row(r) for r in (load(d, b) for b in batches) if r]
        if not rows:
            continue
        print('### %s\n' % (name[0].upper() + name[1:]))
        print('| ' + ' | '.join(HEAD) + ' |')
        print('|' + '---|' * len(HEAD))
        for r in rows + ([total(rows)] if len(rows) > 1 else []):
            print('| ' + ' | '.join(str(r[c]) for c in COLS) + ' |')
        print()


if __name__ == '__main__':
    main()
