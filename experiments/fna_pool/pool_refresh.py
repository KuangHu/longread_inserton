"""Refresh the wave-1 family pools: new / updated assemblies and new long-read runs since the frozen pools.

commands  write the shell script for lrc-xfer (network; started by the user, outside SLURM): per family,
          build_pool fetch + build (assembly_first_v1) into a dated refresh directory, then download_fna run on the
          family's existing data root with the refreshed manifest. download_fna only fetches rows that are not
          verified there already, so only the gap (new or updated accessions) is downloaded.
diff      no network. Frozen pool vs refreshed pool per family, by BioSample:
            new_biosample        in the refreshed pool only
            accession_updated    chosen accession (or its version) differs
            unchanged
            removed              in the frozen pool only (suppressed, replaced or now excluded; reason from the
                                 refreshed excluded table when listed)
          and runs: new usable long-read runs (run accession not in the frozen runs table) per pool BioSample.
          Writes <out>/<family>_delta.tsv, <out>/<family>_new_runs.tsv and <out>/summary.json; the download gap is
          the new_biosample + accession_updated rows.
"""
import argparse
import csv
import gzip
import json
import time
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
FROZEN = HERE / 'scaleup_stage1_20261026'
SCR = Path('/global/scratch/users/kh36969/longread_callout/fna_pool')
FAMILIES = (('microbacteriaceae', 85023), ('actinomycetaceae', 2049), ('flavobacteriaceae', 49546),
            ('eggerthellaceae', 1643826), ('lachnospiraceae', 186803), ('comamonadaceae', 80864),
            ('nitrobacteraceae', 41294), ('micrococcaceae', 1268), ('metamycoplasmataceae', 2895623),
            ('erwiniaceae', 1903409))


def read_tsv(p):
    op = gzip.open if str(p).endswith('.gz') else open
    with op(p, 'rt') as f:
        return list(csv.DictReader(f, delimiter='\t'))


def write_tsv(p, rows, cols):
    with open(p, 'w') as f:
        w = csv.DictWriter(f, cols, delimiter='\t', lineterminator='\n', extrasaction='ignore')
        w.writeheader()
        w.writerows(rows)


def cmd_commands(a):
    tag = a.tag
    L = ['#!/bin/bash', '# lrc-xfer only (network); generated by pool_refresh.py commands on %s' % time.strftime('%F'),
         'set -euo pipefail', 'cd %s' % HERE.parents[1],
         'PY=${PY:-python3}']
    for fam, taxon in FAMILIES:
        if a.families and fam not in a.families.split(','):
            continue
        work = SCR / ('refresh_%s' % tag) / fam
        out = 'experiments/fna_pool/refresh_%s/%s' % (tag, fam)
        data = SCR / 'scaleup_stage1_20261026' / fam / 'data'
        L += ['echo "[$(date -Is)] %s fetch"' % fam,
              '$PY experiments/fna_pool/build_pool.py fetch --taxon %d --work %s' % (taxon, work),
              '$PY experiments/fna_pool/build_pool.py build --taxon %d --work %s --out %s --selection assembly_first_v1'
              % (taxon, work, out)]
        if a.download:
            L += ['echo "[$(date -Is)] %s download gap"' % fam,
                  '$PY experiments/fna_pool/download_fna.py run --manifest %s/download_manifest.tsv --data %s'
                  % (out, data),
                  '$PY experiments/fna_pool/download_fna.py report --manifest %s/download_manifest.tsv --data %s '
                  '--out %s/s1' % (out, data, out)]
    Path(a.out).write_text('\n'.join(L) + '\n')
    print(a.out)


def cmd_diff(a):
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    summ = {}
    for fam, _ in FAMILIES:
        new_dir = Path(a.refreshed) / fam
        if not (new_dir / 'pool.tsv').exists():
            summ[fam] = 'not_refreshed'
            continue
        old = {r['biosample']: r for r in read_tsv(FROZEN / fam / 'pool.tsv')}
        new = {r['biosample']: r for r in read_tsv(new_dir / 'pool.tsv')}
        excl = {}
        if (new_dir / 'excluded.tsv.gz').exists():
            for r in read_tsv(new_dir / 'excluded.tsv.gz'):
                excl[r.get('biosample', '')] = r.get('reason', '')
        rows = []
        for bs in sorted(set(old) | set(new)):
            o, n = old.get(bs), new.get(bs)
            if o and n:
                st = 'unchanged' if o['download_accession'] == n['download_accession'] else 'accession_updated'
            elif n:
                st = 'new_biosample'
            else:
                st = 'removed'
            rows.append(dict(family=fam, biosample=bs, status=st, frozen_accession=(o or {}).get('download_accession', ''),
                             refreshed_accession=(n or {}).get('download_accession', ''),
                             assembly_level=(n or o)['assembly_level'], removed_reason=excl.get(bs, '') if st == 'removed'
                             else '', n_usable_runs=(n or {}).get('n_usable_runs', '')))
        write_tsv(out / ('%s_delta.tsv' % fam), rows, list(rows[0]))
        oruns = {r['run_accession'] for r in read_tsv(FROZEN / fam / 'runs.tsv')}
        nr = [r for r in read_tsv(new_dir / 'runs.tsv') if r['run_accession'] not in oruns]
        write_tsv(out / ('%s_new_runs.tsv' % fam), nr, list(nr[0]) if nr else ['run_accession'])
        st = Counter(r['status'] for r in rows)
        summ[fam] = dict(frozen_pool=len(old), refreshed_pool=len(new), status=dict(st),
                         download_gap=st['new_biosample'] + st['accession_updated'], new_runs=len(nr),
                         new_runs_in_pool_samples=sum(r['sample_accession'] in new for r in nr))
    (out / 'summary.json').write_text(json.dumps(summ, indent=1) + '\n')
    print(json.dumps(summ, indent=1))


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sp = p.add_subparsers(dest='cmd')
    sp.required = True  # Python 3.6 (lrc-xfer) has no required= here
    x = sp.add_parser('commands')
    x.add_argument('--tag', required=True, help='e.g. 20261108')
    x.add_argument('--out', required=True)
    x.add_argument('--families', default='')
    x.add_argument('--download', action='store_true', help='also download the gap after each refresh')
    x = sp.add_parser('diff')
    x.add_argument('--refreshed', required=True, help='repo dir with <family>/pool.tsv of the refresh')
    x.add_argument('--out', required=True)
    a = p.parse_args()
    dict(commands=cmd_commands, diff=cmd_diff)[a.cmd](a)


if __name__ == '__main__':
    main()
